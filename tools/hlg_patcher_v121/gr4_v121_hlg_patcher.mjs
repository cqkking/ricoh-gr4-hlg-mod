var FirmwareError = class extends Error {
  code;
  checks;
  constructor(code, message, checks) {
    super(message ? `${code}: ${message}` : code);
    this.name = "FirmwareError";
    this.code = code;
    if (checks) this.checks = checks;
  }
};

